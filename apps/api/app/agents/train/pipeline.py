"""Train turn pipeline orchestrator.

Coordinates Scrubber -> Observer -> Server Rules -> Scammer -> Persistence.
Follows docs/4.agents.md §3.6 and docs/3.backend.md §7.
"""

import json
from collections.abc import AsyncGenerator
from datetime import UTC, datetime
from typing import Any

from app.agents.runtime import run_observer, run_scammer
from app.config import settings
from app.schemas.common import TraceEvent
from app.schemas.scenario import ScenarioSpec
from app.schemas.train import (
    AckData,
    ChatMessage,
    MessageEndData,
    SendMessageResponse,
    SessionEndData,
    StateData,
    TokenData,
    TurnAssessment,
)
from app.services.safety import detect_distress, validate_scammer_output
from app.services.scrubber import scrubber


def format_transcript_text(messages: list[dict[str, Any]]) -> str:
    lines = []
    for m in messages:
        role = str(m.get("role", "")).upper()
        text = str(m.get("text", ""))
        lines.append(f"{role}: {text}")
    return "\n".join(lines)


class TrainPipeline:
    @staticmethod
    async def process_turn_stream(
        session: dict[str, Any],
        scenario: ScenarioSpec,
        user_text: str,
        client_msg_id: str,
        trace_enabled: bool = False,
    ) -> AsyncGenerator[tuple[str, Any], None]:
        """Yield (event_name, data_object) tuples for SSE streaming.

        Yields:
        - ('ack', AckData)
        - ('trace', TraceEvent) [optional]
        - ('state', StateData)
        - ('token', TokenData)
        - ('message_end', MessageEndData)
        - ('session_end', SessionEndData) [if terminal]
        - ('done', {})
        """
        trace_events: list[TraceEvent] = []

        def on_trace(ev: TraceEvent) -> None:
            if trace_enabled and settings.TRACE_ENABLED:
                trace_events.append(ev)

        # 1. Scrub user text
        scrub_result = scrubber.scrub(user_text, mode="train")
        scrubbed_text = scrub_result.text
        pii_found = scrub_result.found_types

        messages: list[dict[str, Any]] = session.get("messages", [])
        assessments: list[dict[str, Any]] = session.get("assessments", [])
        current_stage = session.get("stage", "hook")
        current_tension = int(session.get("tension", 0))
        difficulty = int(session.get("difficulty", 3))
        lang = session.get("lang", "en")

        user_turn_count = len([m for m in messages if m.get("role") == "user"]) + 1
        turn_index = len(messages) + 1

        # Check safety distress
        distress_detected = detect_distress(user_text)

        # 2. Yield ACK
        ack_data = AckData(
            i=turn_index,
            text=scrubbed_text,
            pii_removed=pii_found,
        )
        yield ("ack", ack_data)

        # 3. Observer assessment
        prev_assessment = assessments[-1] if assessments else None
        compact_flags = [f.id for f in scenario.ground_truth_flags]

        obs_context = {
            "scenario_title": scenario.get_title(lang),
            "scenario_objective": scenario.objective,
            "flags_compact": compact_flags,
            "verification_actions": scenario.verification_actions,
            "stage": current_stage,
            "turn_index": user_turn_count,
            "difficulty": difficulty,
            "prev_assessment_json": json.dumps(prev_assessment) if prev_assessment else "none",
            "prev_tension": current_tension,
            "weak_tactics": session.get("weakTactics", []),
            "transcript_text": format_transcript_text(messages),
            "last_user_text": scrubbed_text,
            "pii_found": pii_found,
            "lang": lang,
            "run_id": f"turn_{turn_index}",
        }

        assessment: TurnAssessment = await run_observer(obs_context, on_trace=on_trace)

        # Drain any trace events generated by Observer
        while trace_events:
            yield ("trace", trace_events.pop(0))

        # 4. Server rules overrides (code layer)
        # Any OTP/PIN/CVV/Card provided in pressure or extraction -> force terminal=user_fell
        high_risk_leaked = any(p in ["otp", "upi_pin", "pin", "cvv", "card"] for p in pii_found)
        if high_risk_leaked and current_stage in ("pressure", "extraction"):
            assessment.terminal = "user_fell"
            assessment.rationale = "Sensitive authentication credentials entered directly."

        # Maximum turns check (14 user turns)
        if user_turn_count >= 14 and assessment.terminal == "none":
            assessment.terminal = "max_turns"
            assessment.rationale = "Maximum simulation turns reached."

        # Safety distress trigger
        if distress_detected or assessment.safety_concern:
            session["safety_break"] = True

        is_terminal = assessment.terminal != "none"
        new_stage = assessment.next_stage if not is_terminal else current_stage
        new_tension = assessment.tension

        # 5. Yield STATE
        state_data = StateData(
            turn=user_turn_count,
            tension=new_tension,
            stage=new_stage,
            status="ending" if is_terminal else "active",
        )
        yield ("state", state_data)

        # 6. Scammer reply
        scam_context = {
            "persona_name": scenario.persona.name,
            "persona_voice": scenario.persona.voice,
            "channel": scenario.channel,
            "fake_entities": scenario.fake_entities.model_dump(),
            "safety_break": session.get("safety_break", False),
            "stage": new_stage,
            "tactic_to_use": assessment.tactic_to_use,
            "pressure_recommendation": assessment.pressure_recommendation,
            "user_action": assessment.user_action,
            "suspicion_level": assessment.suspicion_level,
            "difficulty": difficulty,
            "weak_tactics_top": session.get("weakTactics", ["urgency"])[0] if session.get("weakTactics") else "urgency",
            "scenario": scenario,
            "scenario_objective": scenario.objective,
            "transcript_text": format_transcript_text(
                messages + [{"role": "user", "text": scrubbed_text}]
            ),
            "turn_index": user_turn_count,
            "lang": lang,
            "language_rule": "Reply in English." if lang == "en" else "Reply in Hindi/Hinglish as appropriate.",
            "run_id": f"turn_{turn_index}",
        }

        full_scammer_tokens: list[str] = []
        async for token in run_scammer(scam_context, on_trace=on_trace):
            full_scammer_tokens.append(token)
            yield ("token", TokenData(delta=token))

        # Drain trace events
        while trace_events:
            yield ("trace", trace_events.pop(0))

        raw_scammer_text = "".join(full_scammer_tokens).strip()

        # Output filter check
        is_valid, reason = validate_scammer_output(raw_scammer_text, scenario.fake_entities)
        if not is_valid:
            # Fall back to pre-authored line from scenario
            fallback = scenario.fallback_lines.get(new_stage) or scenario.fallback_lines.get("pressure") or "Please confirm your details."
            final_scammer_text = fallback
        else:
            final_scammer_text = raw_scammer_text

        scammer_turn_index = turn_index + 1
        role: Any = "sensei" if final_scammer_text.startswith("[Sensei]") else "scammer"
        message_end = MessageEndData(
            i=scammer_turn_index,
            text=final_scammer_text,
            role=role,
        )
        yield ("message_end", message_end)

        # 7. Session End event if terminal
        session_end = None
        if is_terminal:
            session_end = SessionEndData(
                outcome=assessment.terminal,  # type: ignore
                reason=assessment.rationale,
            )
            yield ("session_end", session_end)

        # 8. Done event
        yield ("done", {})

        # Update session object in-memory for caller
        now_ts = datetime.now(UTC).isoformat()
        session["tension"] = new_tension
        session["stage"] = new_stage
        session["turn_count"] = user_turn_count
        if "messages" not in session:
            session["messages"] = []
        session["messages"].append(
            {
                "i": turn_index,
                "role": "user",
                "text": scrubbed_text,
                "ts": now_ts,
                "piiRemoved": pii_found,
            }
        )
        session["messages"].append(
            {
                "i": scammer_turn_index,
                "role": role,
                "text": final_scammer_text,
                "ts": now_ts,
            }
        )
        if "assessments" not in session:
            session["assessments"] = []
        session["assessments"].append(assessment.model_dump())
        if is_terminal:
            session["status"] = "ended"
            session["outcome"] = assessment.terminal

    @classmethod
    async def process_turn_sync(
        cls,
        session: dict[str, Any],
        scenario: ScenarioSpec,
        user_text: str,
        client_msg_id: str,
    ) -> SendMessageResponse:
        """Process turn in synchronous / stream=false mode."""
        ack_data = None
        state_data = None
        message_end = None
        session_end = None

        async for ev_name, data in cls.process_turn_stream(
            session, scenario, user_text, client_msg_id, trace_enabled=False
        ):
            if ev_name == "ack":
                ack_data = data
            elif ev_name == "state":
                state_data = data
            elif ev_name == "message_end":
                message_end = data
            elif ev_name == "session_end":
                session_end = data

        now_ts = datetime.now(UTC).isoformat()
        chat_msg = ChatMessage(
            i=message_end.i if message_end else 0,
            role=message_end.role if message_end else "scammer",
            text=message_end.text if message_end else "",
            ts=now_ts,
        )

        return SendMessageResponse(
            ack=ack_data or AckData(i=1, text=user_text),
            state=state_data or StateData(turn=1, tension=0, stage="hook", status="active"),
            message=chat_msg,
            session_end=session_end,
        )
